"""clientlib-<theme>: the AEM client library that carries the theme's CSS/JS.

Layout follows the hand-built site clientlibs this tool was first used with:

    clientlib-<theme>/
      .content.xml              cq:ClientLibraryFolder (categories, dependencies…)   generated
      css.txt                   #base=styles  → index.less                           starter
      js.txt                    #base=scripts → site.js                              starter
      styles/index.less         imports variables, design-system, base, style_system  starter
      styles/variables.less     breakpoints, fonts, resource URL                      starter
      styles/design-system/     tokens, spacing, grid, fonts, typography, variants    generated from Figma
      styles/base.less          html/body defaults                                    starter
      styles/style_system/index.less       imports every component file              generated
      styles/style_system/<p>foundation.less  shared mixins                           starter
      styles/style_system/<p>*.less        one per style (lessgen.scaffold)           starter
      scripts/site.js           DOM-ready entry point                                 starter

"generated" files are derived from project.json/styles.json and rewritten on every
run, so edit the config instead. "starter" files are written once and then belong
to the developer, like the scaffold-less output.
"""
import re
from dataclasses import dataclass
from pathlib import Path

from . import designsystem, jcr, lessgen
from .config import ConfigError

THEME_PATTERN = re.compile(r"^[a-z][a-z0-9-]*$")  # also a JS namespace, so no leading digit
DEFAULT_CSS_PROCESSOR = ("default:none", "min:gcc")
STYLE_SYSTEM = "styles/style_system"
DESIGN_SYSTEM = "styles/design-system"
GENERATED_HEADER = "// Generated by figma2aem clientlib; rewritten on every run. Add imports in styles/index.less."


@dataclass(frozen=True)
class ClientlibSpec:
    theme: str
    categories: tuple
    dependencies: tuple
    embed: tuple
    css_processor: tuple
    js_processor: tuple
    apps_path: str  # e.g. /apps/mysite/clientlibs; "" when not configured
    allow_proxy: bool = True

    @property
    def name(self):
        return f"clientlib-{self.theme}"

    @property
    def jcr_path(self):
        if not self.apps_path:
            raise ConfigError("project.json clientlib.appsPath is required (e.g. /apps/mysite/clientlibs)")
        return f"{self.apps_path.rstrip('/')}/{self.name}"

    @property
    def resources_url(self):
        """Proxy URL of resources/ (allowProxy serves /apps/x via /etc.clientlibs/x)."""
        if not self.apps_path:
            return ""
        return "/etc.clientlibs/" + self.jcr_path.removeprefix("/apps/") + "/resources/"


def _str_list(config, key, default=()):
    value = config.get(key, list(default))
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, list) or not all(isinstance(v, str) and v for v in value):
        raise ConfigError(f"project.json clientlib.{key} must be a list of non-empty strings")
    return tuple(value)


def load_spec(config, theme_override=None):
    """Build the spec from project.json "clientlib" (theme may come from --theme)."""
    config = config or {}
    theme = theme_override or config.get("theme")
    if not theme:
        raise ConfigError("Set project.json clientlib.theme or pass --theme <name>")
    if not THEME_PATTERN.match(theme):
        raise ConfigError(f"Theme '{theme}' must start with a letter and use only a-z, 0-9 and '-' (it names clientlib-{theme})")
    apps_path = config.get("appsPath", "")
    if apps_path and not apps_path.startswith("/apps/"):
        raise ConfigError(f"clientlib.appsPath must start with /apps/, got '{apps_path}'")
    return ClientlibSpec(
        theme=theme,
        categories=_str_list(config, "categories", [f"{theme}.site"]),
        dependencies=_str_list(config, "dependencies"),
        embed=_str_list(config, "embed"),
        css_processor=_str_list(config, "cssProcessor", DEFAULT_CSS_PROCESSOR),
        js_processor=_str_list(config, "jsProcessor"),
        apps_path=apps_path,
        allow_proxy=bool(config.get("allowProxy", True)),
    )


# -- generated files ---------------------------------------------------------------------
def content_xml(spec):
    props = {"jcr:primaryType": "cq:ClientLibraryFolder",
             "allowProxy": spec.allow_proxy,
             "categories": list(spec.categories),
             "cssProcessor": list(spec.css_processor)}
    if spec.js_processor:
        props["jsProcessor"] = list(spec.js_processor)
    props["dependencies"] = list(spec.dependencies)
    props["embed"] = list(spec.embed)
    return jcr.document(props, prefixes=("jcr", "cq"))


def style_system_index(component_files, existing_files, prefix):
    """Foundation first (components override its hooks), then styles.json order,
    then any other .less the developer added to the folder."""
    foundation = f"{prefix}foundation.less"
    ordered = [foundation]
    for name in list(component_files) + sorted(existing_files):
        if name not in ordered and name != "index.less":
            ordered.append(name)
    return "\n".join([GENERATED_HEADER, *(f'@import "{name}";' for name in ordered)]) + "\n"


# -- starter files -----------------------------------------------------------------------
def _manifest(base, entry):
    return f"#base={base}\n{entry}\n"


def starter_files(spec, prefix):
    mq = f"@{prefix}mq"
    resources = (f"@resources-url: '{spec.resources_url}';\n" if spec.resources_url
                 else "// @resources-url: '/etc.clientlibs/<app>/clientlibs/" + spec.name + "/resources/';\n")
    namespace = re.sub(r"\W", "_", spec.theme)
    return {
        "css.txt": _manifest("styles", "index.less"),
        "js.txt": _manifest("scripts", "site.js"),
        "styles/index.less": (
            f"// {spec.name}: entry point listed in css.txt.\n"
            '@import "variables.less";\n'
            '@import "design-system/index.less";\n'
            '@import "base.less";\n'
            '@import "style_system/index.less";\n'),
        "styles/variables.less": (
            "// LESS-only values (breakpoints are generated in design-system/grid.less).\n"
            + resources +
            '@font-default-family: "Helvetica Neue", Helvetica, Arial, sans-serif;\n'
            "@font-default-size: 16px;\n"),
        "styles/base.less": (
            "html,\nbody {\n"
            "    margin: 0;\n"
            "    // html stays at 16px: it is the rem base for this clientlib.\n"
            "    font-size: @font-default-size;\n"
            "    font-family: @font-default-family;\n"
            "}\n"),
        f"{STYLE_SYSTEM}/{prefix}foundation.less": (
            "// Shared by every component file: parametric mixins only (no author classes\n"
            "// here; those belong to registered styles). Figma-derived mixins live in\n"
            f"// ../design-system/: .{prefix}type--*(), .{prefix}variant--*(), .{prefix}grid(),\n"
            f"// and the {mq}-* breakpoints.\n"),
        "scripts/site.js": (
            "'use strict';\n\n"
            f"var {namespace} = window.{namespace} || {{}};\n\n"
            f"{namespace}.init = function () {{\n"
            "    // Behaviour for this theme's components goes here.\n"
            "};\n\n"
            "if (document.readyState !== 'loading') {\n"
            f"    {namespace}.init();\n"
            "} else {\n"
            f"    document.addEventListener('DOMContentLoaded', {namespace}.init);\n"
            "}\n"),
    }


# -- writing -----------------------------------------------------------------------------
def _write(path, text, overwrite):
    if path.exists() and not overwrite:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def generate(spec, styles_spec, page_spec, out_dir, prefix, snapshot=None, design=None):
    """Write clientlib-<theme> under out_dir. Returns (folder, [(path, status)], report text).

    snapshot: Figma snapshot for the design-system layer (None → empty, still compiles).
    design: project.json clientlib options for it (breakpoints, tokenScope, componentMap).
    """
    folder = Path(out_dir).expanduser() / spec.name
    results = []
    design = design or {}

    def record(rel, text, overwrite):
        path = folder / rel
        existed = path.exists()
        written = _write(path, text, overwrite)
        results.append((path, "updated" if existed and written else "created" if written else "exists, kept"))

    record(".content.xml", content_xml(spec), overwrite=True)
    for rel, text in starter_files(spec, prefix).items():
        record(rel, text, overwrite=False)

    component_files = []
    for entries in styles_spec["styles"].values():
        for entry in entries:
            name, text = lessgen.scaffold(styles_spec, page_spec, entry["key"], file_prefix=prefix)
            if name not in component_files:
                component_files.append(name)
                record(f"{STYLE_SYSTEM}/{name}", text, overwrite=False)

    existing = [p.name for p in (folder / STYLE_SYSTEM).glob("*.less")]
    record(f"{STYLE_SYSTEM}/index.less", style_system_index(component_files, existing, prefix), overwrite=True)

    font_dir = folder / "resources" / "fonts"
    files, report, _ = designsystem.build(
        snapshot, prefix, breakpoints=design.get("breakpoints"), scope=design.get("tokenScope", ":root"),
        resources_url=spec.resources_url, font_files=[p.name for p in font_dir.glob("*")] if font_dir.is_dir() else (),
        component_map=design.get("componentMap"))
    for name, text in files.items():
        record(f"{DESIGN_SYSTEM}/{name}", text, overwrite=True)
    return folder, results, report


def package_entries(spec, folder):
    """{zip path: bytes} for every file in the clientlib folder (including developer edits)."""
    root = f"jcr_root{spec.jcr_path}"
    return {f"{root}/{path.relative_to(folder).as_posix()}": path.read_bytes()
            for path in sorted(Path(folder).rglob("*"))
            if path.is_file() and path.name != ".DS_Store"}
