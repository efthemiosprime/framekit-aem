"""Design system layer of clientlib-<theme>, derived from Figma.

Input is a *snapshot* (see figma_snapshot / FigmaClient): the Variables API
response when the plan allows it, plus the node payloads of the breakpoint
frames (page.json verify viewports) and any extra frames (a Foundations or
Components page). Everything here is pure, so it is tested offline.

Output, one LESS file each (all rewritten on every run):

  tokens.less      Figma variables → custom properties (default mode on :root,
                   Desktop/Tablet/Mobile modes as media-query overrides, other
                   modes under [data-<collection>="<mode>"]); fill + effect styles
  spacing.less     gaps / paddings used in the frames but not bound to a variable
  grid.less        breakpoints (@<p>mq-*) and the column grid of every breakpoint frame
  fonts.less       @font-face for every family / weight / style the text uses
  typography.less  one parametric mixin per text style (.<p>type--<name>())
  variants.less    one parametric mixin per component variant (.<p>variant--<set>--<variant>())

Mixins emit no CSS on their own and are not author classes, so the Style
System coverage check ignores them; component files in style_system/ call them.

Figma REST shapes used here follow developers.figma.com (TypeStyle, LayoutGrid,
Effect, Paint, Variables). Two shapes the docs leave open are read defensively:
node `styles` keys in any case ("fill"/"FILL"), and node `boundVariables`
values as one alias or a list of aliases.
"""
import math
import re
from collections import Counter, OrderedDict

DEFAULT_BREAKPOINTS = OrderedDict([("tablet", 1023), ("mobile", 767)])  # max-width per mode, widest first
GENERATED = "// Generated by figma2aem clientlib from Figma; rewritten on every run. Do not edit."
GENERIC_FAMILIES = ("serif", "sans-serif", "monospace")
UNITLESS_SCOPES = {"FONT_WEIGHT", "OPACITY"}
UNITLESS_NAME = re.compile(r"weight|opacity|z-index|ratio|scale|columns?\b|count", re.I)
JUSTIFY = {"MIN": "flex-start", "CENTER": "center", "MAX": "flex-end", "SPACE_BETWEEN": "space-between"}
ALIGN = {"MIN": "flex-start", "CENTER": "center", "MAX": "flex-end", "BASELINE": "baseline"}
TEXT_CASE = {"UPPER": "uppercase", "LOWER": "lowercase", "TITLE": "capitalize"}


# -- small helpers -----------------------------------------------------------------------
def slug(text):
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", str(text))  # camelCase → camel-case
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "x"


def num(value):
    value = round(float(value), 3)
    return str(int(value)) if value == int(value) else f"{value:g}"


def px(value):
    return "0" if float(value) == 0 else f"{num(value)}px"


def color(rgba, opacity=1.0):
    r, g, b = (round(rgba.get(k, 0) * 255) for k in "rgb")
    a = round(rgba.get("a", 1) * opacity, 3)
    return f"#{r:02x}{g:02x}{b:02x}" if a >= 1 else f"rgba({r}, {g}, {b}, {num(a)})"


def alias_ids(value):
    """VariableAlias ids from a boundVariables value (one alias or a list)."""
    items = value if isinstance(value, list) else [value]
    return [v["id"] for v in items if isinstance(v, dict) and v.get("type") == "VARIABLE_ALIAS" and v.get("id")]


def node_style_id(node, kind):
    for key, style_id in (node.get("styles") or {}).items():
        if key.lower().rstrip("s") == kind:
            return style_id
    return None


def walk(node, parent=None, inside_instance=False):
    """Yield (node, parent, inside_instance), skipping hidden layers."""
    if node.get("visible", True) is False:
        return
    yield node, parent, inside_instance
    inside = inside_instance or node.get("type") == "INSTANCE"
    for child in node.get("children", []):
        yield from walk(child, node, inside)


# -- breakpoints -------------------------------------------------------------------------
def breakpoint_for_width(width, breakpoints):
    """Mode of a frame by its width: wider than every max-width → desktop."""
    mode = "desktop"
    for name, max_width in breakpoints.items():
        if width <= max_width:
            mode = name
    return mode


def mode_breakpoint(mode_name, breakpoints):
    name = mode_name.lower()
    for candidate in ["desktop", *breakpoints]:
        if candidate in name:
            return candidate
    return None


# -- variables ---------------------------------------------------------------------------
class Variables:
    """Figma variables → CSS custom property names and per-mode values."""

    def __init__(self, meta, breakpoints):
        meta = meta or {}
        self.variables = meta.get("variables", {}) or {}
        self.collections = meta.get("variableCollections", {}) or {}
        self.breakpoints = breakpoints
        self.names = self._names()

    def _names(self):
        wanted = {}
        for vid, var in self.variables.items():
            web = (var.get("codeSyntax") or {}).get("WEB", "")
            match = re.search(r"--[\w-]+", web)
            wanted[vid] = match.group(0)[2:] if match else slug(var["name"])
        counts = Counter(wanted.values())
        names = {}
        for vid, name in wanted.items():
            if counts[name] > 1:  # same name in two collections: qualify with the collection
                coll = self.collections.get(self.variables[vid].get("variableCollectionId"), {})
                name = f"{slug(coll.get('name', 'collection'))}-{name}"
            names[vid] = name
        return names

    def ref(self, vid):
        return f"var(--{self.names[vid]})" if vid in self.names else None

    def value(self, var, raw):
        if isinstance(raw, dict) and raw.get("type") == "VARIABLE_ALIAS":
            return self.ref(raw.get("id")) or f"/* unresolved alias {raw.get('id')} */ initial"
        kind = var.get("resolvedType")
        if kind == "COLOR":
            return color(raw)
        if kind == "FLOAT":
            unitless = UNITLESS_SCOPES & set(var.get("scopes") or []) or UNITLESS_NAME.search(var["name"])
            return num(raw) if unitless else px(raw)
        if kind == "STRING":
            return '"' + str(raw).replace('"', '\\"') + '"'
        return None  # BOOLEAN has no CSS meaning

    def blocks(self):
        """{"root": [(name, value, is_alias)], ("media", bp): [...], ("attr", coll, mode): [...]}."""
        out = OrderedDict([("root", [])])
        skipped = []
        for vid, var in sorted(self.variables.items(), key=lambda kv: self.names[kv[0]]):
            coll = self.collections.get(var.get("variableCollectionId"))
            if not coll:
                skipped.append(var["name"])
                continue
            values = var.get("valuesByMode", {})
            default = values.get(coll.get("defaultModeId"))
            default_css = self.value(var, default) if default is not None else None
            if default_css is None:
                skipped.append(var["name"])
                continue
            name = self.names[vid]
            is_alias = isinstance(default, dict)
            out["root"].append((name, default_css, is_alias))
            for mode in coll.get("modes", []):
                if mode["modeId"] == coll.get("defaultModeId") or mode["modeId"] not in values:
                    continue
                css = self.value(var, values[mode["modeId"]])
                if css is None:
                    continue
                bp = mode_breakpoint(mode["name"], self.breakpoints)
                if bp == "desktop":
                    continue  # desktop is the default rendering
                key = ("media", bp) if bp and bp != "desktop" else ("attr", slug(coll["name"]), slug(mode["name"]))
                out.setdefault(key, []).append((name, css, isinstance(values[mode["modeId"]], dict)))
        return out, skipped


# -- extraction --------------------------------------------------------------------------
class Extractor:
    def __init__(self, snapshot, breakpoints=None):
        self.breakpoints = OrderedDict(breakpoints or DEFAULT_BREAKPOINTS)
        self.vars = Variables(snapshot.get("variables"), self.breakpoints)
        self.frames = snapshot.get("frames", [])
        self.styles = {}
        self.components, self.component_sets = {}, {}
        for frame in self.frames:
            payload = frame["payload"]
            self.styles.update(payload.get("styles") or {})
            self.components.update(payload.get("components") or {})
            self.component_sets.update(payload.get("componentSets") or {})
        self.fill_styles, self.effect_styles, self.text_styles = OrderedDict(), OrderedDict(), OrderedDict()
        self.fonts = OrderedDict()
        self.raw = {"color": Counter(), "spacing": Counter(), "radius": Counter(), "fontSize": Counter()}
        self.needed = {"spacing": set(), "radius": set()}
        self.bound = Counter()
        self.grids = OrderedDict()
        self.variants = OrderedDict()
        self.counting = True  # off while re-reading nodes for variant mixins

    # -- value resolution ------------------------------------------------------------
    def bound_ref(self, node, field):
        ids = alias_ids((node.get("boundVariables") or {}).get(field))
        return self.vars.ref(ids[0]) if ids else None

    def style_token(self, kind, style_id):
        meta = self.styles.get(style_id)
        if not meta:
            return None
        name = slug(meta["name"])
        prefix = {"fill": "color", "effect": "shadow"}[kind]
        return f"--{name if name.startswith(prefix + '-') else f'{prefix}-{name}'}"

    def paint(self, paint):
        if paint.get("visible", True) is False:
            return None
        kind = paint.get("type")
        opacity = paint.get("opacity", 1)
        if kind == "SOLID":
            ids = alias_ids((paint.get("boundVariables") or {}).get("color"))
            if ids and self.vars.ref(ids[0]):
                self.bound["color"] += self.counting
                return self.vars.ref(ids[0])
            value = color(paint["color"], opacity)
            self.raw["color"][value] += self.counting
            return value
        if kind == "GRADIENT_LINEAR" and paint.get("gradientStops"):
            stops = ", ".join(f"{color(s['color'], opacity)} {num(s['position'] * 100)}%" for s in paint["gradientStops"])
            handles = paint.get("gradientHandlePositions") or []
            angle = 180.0
            if len(handles) >= 2:
                dx, dy = handles[1]["x"] - handles[0]["x"], handles[1]["y"] - handles[0]["y"]
                angle = math.degrees(math.atan2(dx, -dy)) % 360
            return f"linear-gradient({num(angle)}deg, {stops})"
        return None

    def fill(self, node, field="fills", style_kind="fill"):
        style_id = node_style_id(node, style_kind) if field == "fills" else None
        if style_id and self.style_token("fill", style_id):
            self.bound["color"] += self.counting
            return f"var({self.style_token('fill', style_id)})"
        for paint in node.get(field) or []:
            value = self.paint(paint)
            if value:
                return value
        return None

    def length(self, node, field, raw_kind):
        ref = self.bound_ref(node, field)
        if ref:
            self.bound[raw_kind] += self.counting
            return ref
        value = node.get(field)
        if not value:
            return None
        self.raw[raw_kind][float(value)] += self.counting
        self.needed[raw_kind].add(float(value))  # spacing.less must define every var handed out
        return f"var(--{'space' if raw_kind == 'spacing' else 'radius'}-{slug(num(value))})"

    def shadow(self, node):
        style_id = node_style_id(node, "effect")
        if style_id and self.style_token("effect", style_id):
            return f"var({self.style_token('effect', style_id)})"
        return effects_css(node.get("effects") or [])

    # -- passes ----------------------------------------------------------------------
    def run(self):
        for frame in self.frames:
            doc = frame["payload"]["document"]
            if frame.get("breakpoint"):
                self.grid(frame, doc)
            for node, parent, inside in walk(doc):
                self.collect_styles(node)
                if node.get("type") == "TEXT":
                    self.text(node)
                if node.get("layoutMode") in ("HORIZONTAL", "VERTICAL"):
                    for field in ("itemSpacing", "paddingTop", "paddingRight", "paddingBottom", "paddingLeft"):
                        self.length(node, field, "spacing")
                if node.get("cornerRadius") and node.get("type") != "TEXT":
                    self.length(node, "cornerRadius", "radius")
                if node.get("type") not in ("TEXT", "VECTOR", "BOOLEAN_OPERATION"):
                    self.fill(node)
                self.variant(node, parent, inside)
        return self

    def collect_styles(self, node):
        for kind, target in (("fill", self.fill_styles), ("effect", self.effect_styles)):
            style_id = node_style_id(node, kind)
            if style_id and style_id in self.styles and style_id not in target:
                if kind == "fill":
                    value = next((v for v in map(self.paint, node.get("fills") or []) if v), None)
                else:
                    value = effects_css(node.get("effects") or [])
                if value:
                    target[style_id] = (self.style_token(kind, style_id), value)

    def text(self, node):
        style = node.get("style") or {}
        family = style.get("fontFamily")
        if family:
            italic = bool(style.get("italic"))
            weight = int(style.get("fontWeight") or 400)
            key = (family, weight, italic)
            self.fonts.setdefault(key, style.get("fontPostScriptName") or "")
        style_id = node_style_id(node, "text")
        meta = self.styles.get(style_id) if style_id else None
        if meta and style_id not in self.text_styles:
            self.text_styles[style_id] = (slug(meta["name"]), meta["name"], style)
        if not meta and style.get("fontSize"):
            self.raw["fontSize"][float(style["fontSize"])] += 1

    def grid(self, frame, doc):
        bp = frame["breakpoint"]
        if bp in self.grids:
            return
        for grid in doc.get("layoutGrids") or []:
            if grid.get("pattern") != "COLUMNS" or grid.get("visible", True) is False:
                continue
            refs = grid.get("boundVariables") or {}

            def val(field, unit=True):
                ids = alias_ids(refs.get(field))
                if ids and self.vars.ref(ids[0]):
                    return self.vars.ref(ids[0])
                return px(grid.get(field, 0)) if unit else num(grid.get(field, 0))

            entry = OrderedDict([("frame", f"{doc.get('name')} ({frame['id']}, {num(frame['width'])}px)"),
                                 ("columns", val("count", unit=False)), ("gutter", val("gutterSize"))])
            if grid.get("alignment") == "CENTER":
                count, section, gutter = grid.get("count", 0), grid.get("sectionSize", 0), grid.get("gutterSize", 0)
                entry["margin"] = "0"
                entry["max-width"] = px(count * section + max(count - 1, 0) * gutter)
            else:
                entry["margin"] = val("offset")
                entry["max-width"] = "none"  # set on every breakpoint: max-width queries nest
            self.grids[bp] = entry
            return

    def variant(self, node, parent, inside_instance):
        kind = node.get("type")
        if kind == "COMPONENT" and parent and parent.get("type") == "COMPONENT_SET":
            set_name, props = parent["name"], parse_variant_name(node["name"])
        elif kind == "INSTANCE" and not inside_instance:
            meta = self.components.get(node.get("componentId"), {})
            set_meta = self.component_sets.get(meta.get("componentSetId"))
            set_name = (set_meta or meta).get("name") or node.get("name")
            props = OrderedDict((k.split("#")[0], v.get("value")) for k, v in (node.get("componentProperties") or {}).items()
                                if v.get("type") == "VARIANT")
        else:
            return
        variants = self.variants.setdefault(set_name, OrderedDict())
        key = tuple(props.items())
        # Definitions (COMPONENT) win over instances, which may carry overrides.
        if key in variants and not (kind == "COMPONENT" and variants[key]["source"] == "INSTANCE"):
            return
        self.counting = False
        try:
            variants[key] = {"source": kind, "node": node["id"], "css": self.box_css(node), "text": self.text_css(node)}
        finally:
            self.counting = True

    def box_css(self, node):
        rules = []
        background = self.fill(node)
        if background:
            rules.append(("background", background))
        stroke = self.fill(node, field="strokes")
        if stroke and node.get("strokeWeight"):
            rules.append(("border", f"{px(node['strokeWeight'])} solid {stroke}"))
        radii = node.get("rectangleCornerRadii")
        if radii and len(set(radii)) > 1:
            rules.append(("border-radius", " ".join(px(r) for r in radii)))
        else:
            radius = self.length(node, "cornerRadius", "radius")
            if radius:
                rules.append(("border-radius", radius))
        mode = node.get("layoutMode")
        if mode in ("HORIZONTAL", "VERTICAL"):
            rules += [("display", "flex"), ("flex-direction", "row" if mode == "HORIZONTAL" else "column")]
            if node.get("layoutWrap") == "WRAP":
                rules.append(("flex-wrap", "wrap"))
            if node.get("primaryAxisAlignItems") in JUSTIFY:
                rules.append(("justify-content", JUSTIFY[node["primaryAxisAlignItems"]]))
            if node.get("counterAxisAlignItems") in ALIGN:
                rules.append(("align-items", ALIGN[node["counterAxisAlignItems"]]))
            gap = self.length(node, "itemSpacing", "spacing")
            if gap and node.get("primaryAxisAlignItems") != "SPACE_BETWEEN":
                rules.append(("gap", gap))
            sides = [self.length(node, f, "spacing") or "0"
                     for f in ("paddingTop", "paddingRight", "paddingBottom", "paddingLeft")]
            if any(s != "0" for s in sides):
                rules.append(("padding", " ".join(sides)))
        shadow = self.shadow(node)
        if shadow:
            rules.append(("box-shadow", shadow))
        if node.get("opacity", 1) < 1:
            rules.append(("opacity", num(node["opacity"])))
        return rules

    def text_css(self, node):
        text = next((n for n, _, _ in walk(node) if n.get("type") == "TEXT"), None)
        if not text:
            return None
        style_id = node_style_id(text, "text")
        meta = self.styles.get(style_id) if style_id else None
        return {"mixin": slug(meta["name"]) if meta else None, "color": self.fill(text),
                "raw": None if meta else text.get("style")}


def parse_variant_name(name):
    props = OrderedDict()
    for part in name.split(","):
        if "=" in part:
            key, value = part.split("=", 1)
            props[key.strip()] = value.strip()
    return props


def effects_css(effects):
    shadows = []
    for effect in effects:
        if effect.get("visible", True) is False or effect.get("type") not in ("DROP_SHADOW", "INNER_SHADOW"):
            continue
        offset = effect.get("offset") or {}
        inset = "inset " if effect["type"] == "INNER_SHADOW" else ""
        shadows.append(f"{inset}{px(offset.get('x', 0))} {px(offset.get('y', 0))} {px(effect.get('radius', 0))} "
                       f"{px(effect.get('spread', 0))} {color(effect.get('color') or {'a': 0.25})}")
    return ", ".join(shadows) or None


# -- snapshot ----------------------------------------------------------------------------
def figma_snapshot(client, viewport_frames, extra_frames=(), breakpoints=None, http_error=Exception):
    """Fetch what build() needs. viewport_frames: [(node id, width)] from page.json verify;
    extra_frames: node ids of Foundations / Components frames (no breakpoint)."""
    breakpoints = OrderedDict(breakpoints or DEFAULT_BREAKPOINTS)
    ids = list(OrderedDict.fromkeys([f for f, _ in viewport_frames] + list(extra_frames)))
    if not ids:
        raise ValueError("No Figma frames: add page.json verify.viewports or clientlib.figmaFrames")
    payloads = client.nodes(ids)
    widths = dict(viewport_frames)
    frames = []
    for node_id in ids:
        payload = payloads.get(node_id) or payloads.get(node_id.replace("-", ":"))
        width = widths.get(node_id)
        frames.append({"id": node_id, "width": width,
                       "breakpoint": breakpoint_for_width(width, breakpoints) if width else None,
                       "payload": payload})
    snapshot = {"fileKey": client.file_key, "frames": frames, "variables": None, "variablesError": None}
    try:
        snapshot["variables"] = client.local_variables()
    except http_error as exc:  # 403 on non-Enterprise plans: fall back to styles
        snapshot["variablesError"] = str(exc)
    return snapshot


# -- rendering ---------------------------------------------------------------------------
def media_query(max_width):
    # Literal, not @<p>mq-*: LESS 1.7.5 (AEM) cannot parse @media @{var}, LESS 4 deprecates @media @var.
    return f"screen and (max-width: {max_width}px)"


def _decls(pairs, indent="    "):
    return [f"{indent}--{name}: {value};" for name, value in pairs]


def _scoped(scope, lines, media=None):
    if not lines:
        return []
    if media:
        return [f"{scope} {{", f"    @media {media} {{", *("    " + l for l in lines), "    }", "}"]
    return [f"{scope} {{", *lines, "}"]


def render_grid(ex, prefix):
    bps = ex.breakpoints
    lines = [GENERATED, "", "// Breakpoints (max-width per mode). LESS variables: media queries cannot read custom properties."]
    widest = next(iter(bps.values()), None)
    if widest:
        lines.append(f'@{prefix}mq-desktop: ~"screen and (min-width: {widest + 1}px)";')
    for name, max_width in bps.items():
        lines.append(f'@{prefix}mq-{name}: ~"screen and (max-width: {max_width}px)";')
    lines.append("")
    if not ex.grids:
        lines.append("// No visible COLUMNS layout grid on the breakpoint frames (page.json verify.viewports).")
    for bp, grid in ex.grids.items():
        lines.append(f"// {bp}: {grid['frame']}")
    root = ex.grids.get("desktop")
    if root:
        lines += _scoped(":root", _decls([(f"grid-{k}", v) for k, v in root.items() if k != "frame"]))
    for bp in bps:
        if bp in ex.grids:
            lines += _scoped(":root", _decls([(f"grid-{k}", v) for k, v in ex.grids[bp].items() if k != "frame"],
                                             "    "), media=media_query(ex.breakpoints[bp]))
    lines += ["", "// Column grid of the design: call inside a container rule.",
              f".{prefix}grid() {{",
              "    display: grid;",
              '    grid-template-columns: ~"repeat(var(--grid-columns, 12), minmax(0, 1fr))";',
              "    column-gap: var(--grid-gutter, 0);",
              "    padding-left: var(--grid-margin, 0);",
              "    padding-right: var(--grid-margin, 0);",
              "    max-width: var(--grid-max-width, none);",
              "    margin-left: auto;",
              "    margin-right: auto;",
              "    box-sizing: border-box;",
              "}", ""]
    return "\n".join(lines)


def render_tokens(ex, prefix, scope):
    blocks, skipped = ex.vars.blocks()
    lines = [GENERATED, ""]
    if not ex.vars.variables:
        lines.append("// No Figma variables in the snapshot (Variables API needs an Enterprise plan); "
                     "tokens below come from styles.")
    root = [(n, v) for n, v, _ in blocks["root"]]
    root += [(token[2:], value) for token, value in ex.fill_styles.values()]
    root += [(token[2:], value) for token, value in ex.effect_styles.values()]
    lines += _scoped(":root", _decls(root)) or [":root {", "}"]
    alias_names = {n for n, _, alias in blocks["root"] if alias}
    # max-width queries nest (mobile also matches tablet), so each mode is compared with
    # the value in effect at the next wider breakpoint, not only with the default.
    effective = {n: v for n, v, _ in blocks["root"]}
    for bp in ex.breakpoints:
        entries = blocks.get(("media", bp), [])
        changed = [(n, v) for n, v, _ in entries if effective.get(n) != v]
        effective.update((n, v) for n, v, _ in entries)
        if scope != ":root":  # aliases are computed where declared: re-declare them inside the scope
            changed += [(n, v) for n, v, _ in blocks["root"] if n in alias_names and n not in dict(changed)]
        if changed:
            lines += [""] + _scoped(scope, _decls(changed), media=media_query(ex.breakpoints[bp]))
    for key, entries in blocks.items():
        if key[0] == "attr":
            default = {n: v for n, v, _ in blocks["root"]}
            changed = [(n, v) for n, v, _ in entries if default.get(n) != v]
            lines += [""] + _scoped(f'[data-{key[1]}="{key[2]}"]', _decls(changed))
    if skipped:
        lines += ["", "// Not emitted (boolean or unresolvable): " + ", ".join(sorted(skipped))]
    return "\n".join(lines) + "\n"


def render_spacing(ex):
    lines = [GENERATED, "",
             "// Gaps, paddings and radii used in the frames that are not bound to a variable.",
             "// Bind them in Figma to fold them into tokens.less."]
    pairs = [(f"space-{slug(num(v))}", px(v)) for v in sorted(ex.needed["spacing"])]
    pairs += [(f"radius-{slug(num(v))}", px(v)) for v in sorted(ex.needed["radius"])]
    return "\n".join(lines + (_scoped(":root", _decls(pairs)) or [":root {", "}"])) + "\n"


def font_file(family, weight, italic, postscript):
    if postscript:
        return postscript
    return re.sub(r"\W", "", family) + f"-{weight}" + ("Italic" if italic else "")


def render_fonts(ex, resources_url, existing_files):
    lines = [GENERATED, ""]
    missing = []
    if not ex.fonts:
        return "\n".join(lines + ["// No text in the snapshot."]) + "\n", missing
    if not resources_url:
        lines.append("// Set project.json clientlib.appsPath to get @font-face rules for resources/fonts/.")
    for (family, weight, italic), postscript in ex.fonts.items():
        name = font_file(family, weight, italic, postscript)
        files = [f for f in (f"{name}.woff2", f"{name}.woff") if f in existing_files]
        if not files:
            missing.append(f"{name}.woff2")
        if not resources_url:
            lines.append(f"// {family} {weight}{' italic' if italic else ''}: resources/fonts/{name}.woff2")
            continue
        srcs = ", ".join(f"url('{resources_url}fonts/{f}') format('{f.rsplit('.', 1)[1]}')"
                         for f in (files or [f"{name}.woff2"]))
        lines += ["@font-face {", f'    font-family: "{family}";', f"    src: {srcs};",
                  f"    font-weight: {weight};", f"    font-style: {'italic' if italic else 'normal'};",
                  "    font-display: swap;", "}"]
    return "\n".join(lines) + "\n", missing


def family_stack(family):
    generic = "monospace" if "mono" in family.lower() else "serif" if re.search(r"serif", family, re.I) and "sans" not in family.lower() else "sans-serif"
    return f'"{family}", {generic}'


def type_rules(style, refs, raw_ok=True):
    """CSS declarations of a Figma TypeStyle; refs maps field → var() when bound."""
    rules = []
    family = refs.get("fontFamily") or (family_stack(style["fontFamily"]) if style.get("fontFamily") else None)
    if family:
        rules.append(("font-family", family))
    if refs.get("fontSize") or style.get("fontSize"):
        rules.append(("font-size", refs.get("fontSize") or px(style["fontSize"])))
    if refs.get("fontWeight") or style.get("fontWeight"):
        rules.append(("font-weight", refs.get("fontWeight") or num(style["fontWeight"])))
    if refs.get("lineHeight"):
        rules.append(("line-height", refs["lineHeight"]))
    elif style.get("lineHeightUnit") == "INTRINSIC_%":
        rules.append(("line-height", "normal"))
    elif style.get("lineHeightUnit") == "FONT_SIZE_%" and style.get("lineHeightPercentFontSize"):
        rules.append(("line-height", num(style["lineHeightPercentFontSize"] / 100)))
    elif style.get("lineHeightPx"):
        rules.append(("line-height", px(style["lineHeightPx"])))
    if refs.get("letterSpacing") or style.get("letterSpacing"):
        rules.append(("letter-spacing", refs.get("letterSpacing") or px(style["letterSpacing"])))
    if style.get("italic"):
        rules.append(("font-style", "italic"))
    if style.get("textCase") in TEXT_CASE:
        rules.append(("text-transform", TEXT_CASE[style["textCase"]]))
    if style.get("textDecoration") == "UNDERLINE":
        rules.append(("text-decoration", "underline"))
    return rules


def render_typography(ex, prefix):
    lines = [GENERATED, "", "// One mixin per Figma text style: .x { ." + prefix + "type--<name>(); }", ""]
    tokens = []
    for _, (name, label, style) in ex.text_styles.items():
        refs = {}
        for field, var in (style.get("boundVariables") or {}).items():
            ids = alias_ids(var)
            if ids and ex.vars.ref(ids[0]):
                refs[field] = ex.vars.ref(ids[0])
        rules = type_rules(style, refs)
        token_rules = []
        for prop, value in rules:
            token = f"type-{name}-{prop}"
            tokens.append((token, value))
            token_rules.append((prop, f"var(--{token})"))
        lines += [f"// {label}", f".{prefix}type--{name}() {{", *(f"    {p}: {v};" for p, v in token_rules), "}", ""]
    if not ex.text_styles:
        lines.append("// No text styles used in the snapshot frames.")
    header, body = lines[:1], lines[1:]
    return "\n".join(header + ([""] + _scoped(":root", _decls(tokens)) if tokens else []) + body) + "\n"


def variant_names(props_list):
    """Short names (values only) unless two variants of a set would collide."""
    short = ["--".join(slug(v) for _, v in props) or "default" for props in props_list]
    if len(set(short)) == len(short):
        return short
    return ["--".join(f"{slug(k)}-{slug(v)}" for k, v in props) or "default" for props in props_list]


def render_variants(ex, prefix, component_map):
    lines = [GENERATED, "", "// One mixin per component variant (Figma definition when present, else first instance).",
             "// Call them from the style_system/ component files.", ""]
    for set_name, variants in ex.variants.items():
        aem = (component_map or {}).get(set_name)
        lines.append(f"// ---- {set_name}" + (f"  → AEM {aem}" if aem else "") + " " + "-" * 20)
        for key, name in zip(variants, variant_names(list(variants))):
            info = variants[key]
            label = ", ".join(f"{k}={v}" for k, v in key) or "(no variants)"
            body = [f"    {p}: {v};" for p, v in info["css"]]
            text = info["text"]
            inner = []
            if text:
                if text["mixin"]:
                    inner.append(f"        .{prefix}type--{text['mixin']}();")
                elif text["raw"]:
                    inner += [f"        {p}: {v};" for p, v in type_rules(text["raw"], {})]
                if text["color"]:
                    inner.append(f"        color: {text['color']};")
            mixin = f".{prefix}variant--{slug(set_name)}--{name}"
            lines += [f"// {label}  (Figma {info['source'].lower()} {info['node']})", f"{mixin}() {{", *body, "}"]
            if text and inner:
                lines += [f"{mixin}--text() {{", *(i[4:] for i in inner), "}"]
            lines.append("")
    if not ex.variants:
        lines.append("// No component instances or component sets in the snapshot frames.")
    return "\n".join(lines) + "\n"


def report(ex, missing_fonts, skipped_vars):
    def top(counter, fmt, n=8):
        return ", ".join(f"{fmt(v)}×{c}" for v, c in counter.most_common(n))

    lines = ["# Design system report", "",
             f"- Variables: {len(ex.vars.variables)} in {len(ex.vars.collections)} collection(s)"
             + (f"; not emitted: {', '.join(sorted(skipped_vars))}" if skipped_vars else ""),
             f"- Styles used: {len(ex.fill_styles)} fill, {len(ex.text_styles)} text, {len(ex.effect_styles)} effect",
             "- Breakpoint grids: " + (", ".join(bp + " (" + g["columns"] + " cols)" for bp, g in ex.grids.items()) or "none"),
             f"- Fonts: {len(ex.fonts)} face(s)" + (f"; missing in resources/fonts: {', '.join(missing_fonts)}" if missing_fonts else ""),
             f"- Component sets: {len(ex.variants)}, variants: {sum(len(v) for v in ex.variants.values())}",
             "", "## Values not bound to a variable or style", "",
             f"- Colors ({sum(ex.raw['color'].values())} uses, bound {ex.bound['color']}): {top(ex.raw['color'], str) or '—'}",
             f"- Spacing ({sum(ex.raw['spacing'].values())} uses, bound {ex.bound['spacing']}): {top(ex.raw['spacing'], px) or '—'}",
             f"- Radii ({sum(ex.raw['radius'].values())} uses, bound {ex.bound['radius']}): {top(ex.raw['radius'], px) or '—'}",
             f"- Font sizes without a text style ({sum(ex.raw['fontSize'].values())} uses): {top(ex.raw['fontSize'], px) or '—'}",
             ""]
    return "\n".join(lines)


def build(snapshot, prefix, *, breakpoints=None, scope=":root", resources_url="", font_files=(), component_map=None):
    """{relative file: text} for styles/design-system/, plus the report text and missing font files."""
    ex = Extractor(snapshot or {}, breakpoints).run()
    _, skipped = ex.vars.blocks()
    fonts, missing = render_fonts(ex, resources_url, set(font_files))
    files = OrderedDict([
        ("tokens.less", render_tokens(ex, prefix, scope)),
        ("spacing.less", render_spacing(ex)),
        ("grid.less", render_grid(ex, prefix)),
        ("fonts.less", fonts),
        ("typography.less", render_typography(ex, prefix)),
        ("variants.less", render_variants(ex, prefix, component_map)),
    ])
    files["index.less"] = "\n".join([GENERATED, *(f'@import "{name}";' for name in files)]) + "\n"
    note = snapshot.get("variablesError") if snapshot else None
    text = report(ex, missing, skipped) + (f"\nVariables API: {note}\n" if note else "")
    return files, text, missing
